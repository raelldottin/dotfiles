#!/usr/bin/env bash
# Runs inside a disposable VM: install Nix, then activate the personal
# nix-darwin `macbook` system as the flake's user, following docs/NIX.md.
#
#   test-personal.sh BUNDLE NIXPKGS_REV USER
#
# USER is the `username` fixed in flake.nix.
# Runs as the image's admin account, creates the flake's personal user,
# and re-runs itself as that user for the activation steps.

# Commands passed to login_shell expand in the guest's login shell.
# shellcheck disable=SC2016

# shellcheck source=vm/guest/common.sh
. "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/common.sh"

# Casks whose installers cannot run in a VM. Multipass needs nested
# virtualization, which Apple's Virtualization framework does not offer.
VM_EXCLUDED_CASKS=(multipass)

# Write a flake that extends .#macbook without the excluded casks, so the rest
# of the configuration activates unchanged. The checkout itself is untouched.
write_vm_flake() {
  local checkout="$1"
  local destination="$2"
  local excluded=""
  local cask

  for cask in "${VM_EXCLUDED_CASKS[@]}"; do
    excluded+=" \"$cask\""
  done
  mkdir -p "$destination"
  cat >"$destination/flake.nix" <<NIX
{
  description = "dotfiles macbook for a test VM (generated by vm/guest/test-personal.sh)";
  inputs.dotfiles.url = "git+file://$checkout";
  outputs = { dotfiles, ... }:
    let
      macbook = dotfiles.darwinConfigurations.macbook;
      excluded = [$excluded ];
    in {
      darwinConfigurations.macbook = macbook.extendModules {
        modules = [
          ({ lib, ... }: {
            # Re-declare the remaining casks without nix-darwin's generated,
            # read-only brewfileLine; every other cask setting is kept.
            homebrew.casks = lib.mkForce (map
              (cask: builtins.removeAttrs cask [ "brewfileLine" ])
              (builtins.filter (cask: !(builtins.elem cask.name excluded))
                macbook.config.homebrew.casks));
          })
        ];
      };
    };
}
NIX
}

as_user() {
  local bundle="$1"
  local nixpkgs_rev="$2"
  local checkout="$HOME/dotfiles"
  local tools="/etc/profiles/per-user/$USER/bin"
  local vm_flake="$HOME/dotfiles-vm-flake"
  local cask

  cd /
  load_nix
  step "Cloning the tested commit to $checkout as $USER"
  clone_bundle "$bundle" "$checkout" "$nixpkgs_rev"
  cd "$checkout"

  step "Checking the flake (docs/NIX.md)"
  run nix "${NIX_FLAGS[@]}" flake check --no-write-lock-file

  step "Test VM flake without casks that cannot install in a VM: ${VM_EXCLUDED_CASKS[*]}"
  write_vm_flake "$checkout" "$vm_flake"
  cat "$vm_flake/flake.nix"

  # docs/NIX.md runs darwin-rebuild from the nix-darwin-26.05 branch, which
  # Nix resolves through the GitHub API. Use the revision pinned in flake.lock
  # instead: it needs no API lookup, so unauthenticated rate limits cannot
  # fail the run, and it is the version the configuration is locked to.
  step "First nix-darwin activation (docs/NIX.md, pinned nix-darwin)"
  run sudo -H "$(command -v nix)" "${NIX_FLAGS[@]}" run --inputs-from . nix-darwin#darwin-rebuild -- \
    switch --flake "$vm_flake#macbook"

  step "Second activation with the installed darwin-rebuild"
  run sudo -H /run/current-system/sw/bin/darwin-rebuild switch --flake "$vm_flake#macbook"

  step "Fresh login shell, tmux, and Neovim"
  login_shell 'for tool in zsh tmux nvim atuin python3 brew; do printf "%s -> %s\n" "$tool" "$(command -v "$tool")"; done'
  login_shell '[[ "$(command -v nvim)" == /etc/profiles/per-user/* ]]' ||
    fail "nvim does not come from the Home Manager profile"
  login_shell 'tmux -L dotfiles-vm new-session -d "sleep 30" && tmux -L dotfiles-vm has-session && tmux -L dotfiles-vm kill-server'
  login_shell 'nvim --headless "+lua io.stdout:write(vim.version().major .. \".\" .. vim.version().minor .. \"\\n\")" +qa'
  [[ -d "$HOME/.config/nvim" ]] || fail "$HOME/.config/nvim was not installed"

  step "Every other Homebrew cask from nix/darwin.nix is installed"
  login_shell 'brew list --cask'
  for cask in $(nix "${NIX_FLAGS[@]}" eval --raw "$vm_flake#darwinConfigurations.macbook.config.homebrew.casks" \
    --apply 'casks: builtins.concatStringsSep " " (map (cask: cask.name) casks)'); do
    login_shell "brew list --cask $(printf '%q' "$cask") >/dev/null" || fail "cask $cask is not installed"
  done

  step "Pinned editor/history probes with the activated tools"
  run_pinned_probes "$checkout" "$tools" "$nixpkgs_rev"

  step "Personal profile test passed"
}

main() {
  local bundle="$1"
  local nixpkgs_rev="$2"
  local user="$3"
  local password

  [[ "$user" =~ ^[a-z_][a-z0-9_-]*$ ]] || fail "invalid personal username: $user"

  install_nix

  if ! id "$user" >/dev/null 2>&1; then
    step "Creating the personal user $user"
    # A throwaway password: the account is only reached through sudo here.
    password="$(openssl rand -base64 24)"
    sudo sysadminctl -addUser "$user" -fullName "Dotfiles VM Personal" \
      -password "$password" -home "/Users/$user" -shell /bin/zsh -admin
    sudo createhomedir -c -u "$user" >/dev/null
  fi
  # Homebrew casks that install packages call sudo during activation.
  printf '%s ALL=(ALL) NOPASSWD: ALL\n' "$user" |
    sudo EDITOR=tee visudo -f "/etc/sudoers.d/$user-nopasswd" >/dev/null

  sudo -H -u "$user" /bin/bash "${BASH_SOURCE[0]}" --as-user "$bundle" "$nixpkgs_rev"
}

if [[ "${1:-}" == "--as-user" ]]; then
  shift
  as_user "$@"
else
  main "$@"
fi
